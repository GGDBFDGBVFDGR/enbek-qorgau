  function answer(index) {
    if (locked) return;
    locked = true;
    picked = index;
    const buttons = document.querySelectorAll(".option");
    buttons.forEach((button, option) => {
      button.disabled = true;
      if (option === QUIZ[qIndex].answer) button.classList.add("is-correct");
    });
    if (index === QUIZ[qIndex].answer) score += 1;
    else buttons[index].classList.add("is-wrong");
    const explain = document.getElementById("explain");
    explain.hidden = false;
    explain.textContent = QUIZ[qIndex][lang].explain;
    document.getElementById("quiz-next").hidden = false;
  }

  function tiltProtocol(event) {
    const card = document.getElementById("protocol");
    if (!card || window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
    const rect = card.getBoundingClientRect();
    const x = (event.clientX - rect.left) / rect.width - 0.5;
    const y = (event.clientY - rect.top) / rect.height - 0.5;
    card.style.transform = `rotateY(${x * 7}deg) rotateX(${-y * 6}deg)`;
  }

  function bind() {
    document.querySelectorAll("[data-set-lang]").forEach((button) => {
      button.addEventListener("click", () => {
        lang = button.dataset.setLang;
        try { localStorage.setItem("eq-lang", lang); } catch (error) { /* ignore */ }
        refresh();
      });
    });
    document.getElementById("theme-toggle").addEventListener("click", () => {
      applyTheme(document.documentElement.dataset.theme === "light" ? "dark" : "light");
    });

    const toggle = document.querySelector(".nav-toggle");
    const nav = document.getElementById("site-nav");
    toggle.addEventListener("click", () => {
      const open = nav.classList.toggle("is-open");
      toggle.setAttribute("aria-expanded", open ? "true" : "false");
      document.body.classList.toggle("nav-open", open);
    });
    nav.querySelectorAll("a").forEach((link) => {
      link.addEventListener("click", () => {
        nav.classList.remove("is-open");
        toggle.setAttribute("aria-expanded", "false");
        document.body.classList.remove("nav-open");
      });
    });

    document.getElementById("topic-list").addEventListener("click", (event) => {
      const button = event.target.closest("[data-topic]");
      if (!button) return;
      topicIndex = Number(button.dataset.topic);
      renderTopics();
    });

    document.getElementById("lab-prev").addEventListener("click", () => goTo(labIndex - 1));
    document.getElementById("lab-next").addEventListener("click", () => goTo(labIndex + 1));
    document.getElementById("ring").addEventListener("click", (event) => {
      const card = event.target.closest("[data-lab]");
      if (!card) return;
      goTo(Number(card.dataset.lab));
    });

    const stage = document.getElementById("stage");
    stage.addEventListener("pointerdown", (event) => {
      dragging = true;
      dragX = event.clientX;
    });
    window.addEventListener("pointerup", () => {
      if (!dragging) return;
      dragging = false;
      goTo(frontIndex());
    });
    window.addEventListener("pointermove", (event) => {
      if (!dragging) return;
      spinTarget += (event.clientX - dragX) * 0.35;
      spin = spinTarget;
      dragX = event.clientX;
      layoutCarousel();
    });

    document.getElementById("lab-detail").addEventListener("click", (event) => {
      const button = event.target.closest("[data-fire]");
      if (!button) return;
      fireKey = button.dataset.fire;
      renderLabDetail();
    });

    document.getElementById("aid-tabs").addEventListener("click", (event) => {
      const button = event.target.closest("[data-aid]");
      if (!button) return;
      aidIndex = Number(button.dataset.aid);
      renderAid();
    });

    const protocol = document.getElementById("protocol");
    protocol.addEventListener("pointermove", tiltProtocol);
    protocol.addEventListener("pointerleave", () => { protocol.style.transform = ""; });

    document.getElementById("quiz").addEventListener("click", (event) => {
      const option = event.target.closest("[data-option]");
      if (option) answer(Number(option.dataset.option));
      if (event.target.id === "quiz-next") {
        if (qIndex >= QUIZ.length - 1) {
          finished = true;
          renderQuiz();
          return;
        }
        qIndex += 1;
        locked = false;
        picked = -1;
        renderQuiz();
      }
      if (event.target.id === "restart") {
        qIndex = 0;
        score = 0;
        locked = false;
        picked = -1;
        finished = false;
        renderQuiz();
      }
    });

    window.addEventListener("resize", layoutCarousel);
  }

  function tick() {
    if (!dragging) spin += (spinTarget - spin) * 0.12;
    layoutCarousel();
    requestAnimationFrame(tick);
  }

