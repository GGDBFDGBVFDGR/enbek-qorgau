  function norm(angle) {
    let value = angle % 360;
    if (value > 180) value -= 360;
    if (value < -180) value += 360;
    return value;
  }

  function frontIndex() {
    const step = 360 / LABS.length;
    let best = 0;
    let bestAbs = 999;
    LABS.forEach((_, index) => {
      const delta = Math.abs(norm(spin + index * step));
      if (delta < bestAbs) {
        bestAbs = delta;
        best = index;
      }
    });
    return best;
  }

  function layoutCarousel() {
    const stage = document.getElementById("stage");
    const cards = stage.querySelectorAll(".lab-card");
    const step = 360 / LABS.length;
    const cardW = cards[0] ? cards[0].offsetWidth : 220;
    const gap = stage.clientWidth < 700 ? 14 : 22;
    const pitch = cardW + gap;
    cards.forEach((card, index) => {
      const offset = norm(spin + index * step) / step;
      const abs = Math.abs(offset);
      const visible = abs < 2.15;
      card.style.transform = `translate3d(${offset * pitch}px, 0, 0)`;
      card.style.opacity = visible ? "1" : "0";
      card.style.zIndex = String(100 - Math.round(abs * 10));
      card.style.pointerEvents = abs < 1.4 ? "auto" : "none";
      card.classList.toggle("is-front", index === labIndex);
      card.setAttribute("aria-pressed", index === labIndex ? "true" : "false");
    });
  }

